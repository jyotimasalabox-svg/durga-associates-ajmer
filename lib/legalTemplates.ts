import { ClientRecord } from './types';

export function generateLegalDraft(client: ClientRecord): { title: string; content: string; checklist: string[] } {
  const p = client.propertyDetails;
  const seller = client.sellerDetails || {
    name: 'श्री [विक्रेता का नाम]',
    fatherName: 'श्री [पिता का नाम]',
    address: 'निवासी अजमेर, राजस्थान',
    phone: '',
    aadhaarOrPan: 'XXXX-XXXX-XXXX'
  };
  const buyer = client.buyerDetails || {
    name: client.clientName || 'श्री [क्रेता का नाम]',
    fatherName: client.fatherOrHusbandName || 'श्री [पिता/पति का नाम]',
    address: client.address || 'निवासी अजमेर, राजस्थान',
    phone: client.phone || '',
    gender: 'male' as const,
    aadhaarOrPan: 'XXXX-XXXX-XXXX'
  };
  const cheque = client.paymentChequeDetails || {
    chequeNo: '[चेक / RTGS संख्या]',
    bankName: '[बैंक शाखा]',
    date: new Date().toLocaleDateString('hi-IN'),
    amount: client.fees.grandTotal || p.considerationValue
  };

  const today = new Date().toLocaleDateString('hi-IN', {
    day: 'numeric',
    month: 'long',
    year: 'numeric'
  });

  const mandatoryChecklist: string[] = [
    'विक्रेता एवं क्रेता दोनों के मूल आधार कार्ड एवं पैन कार्ड (2-2 स्वप्रमाणित छायाप्रतियां)',
    'दोनों पक्षों के 2-2 पासपोर्ट साइज नवीनतम रंगीन फोटो',
    'दो स्वतंत्र वयस्क स्थानीय गवाह (दोनों के मूल आधार कार्ड व 2 छायाप्रतियां)',
    'संपत्ति का मूल स्वामित्व दस्तावेज (पूर्व बैनामा / आवंटन पत्र / मूल पट्टा / जमाबंदी)',
    'अजमेर विकास प्राधिकरण (ADA) अथवा नगर निगम अजमेर / सक्षम प्राधिकारी द्वारा स्वीकृत नक्शा / मौका ट्रेस',
    'नवीनतम राजस्व नकल / जमाबंदी (खेवट/खतौनी) एवं तरमीम (यदि कृषि भूमि हो)',
    'नगर निगम / ग्राम पंचायत का अद्यतन अदेय प्रमाण पत्र (No Dues Certificate / गृहकर रसीद)',
    'प्रतिफल राशि भुगतान का वैधानिक प्रमाण (बैंक चेक, डीडी या आरटीजीएस/नेफ्ट यूटीआर संख्या)',
    'राजस्थान ई-ग्रास (e-Gras) स्टाम्प ड्यूटी एवं पंजीयन शुल्क चालान की मूल प्रति',
    'क्रेता या विक्रेता के कंपनी / फर्म / ट्रस्ट होने पर सक्षम प्रस्ताव (Resolution) एवं अधिकृत हस्ताक्षरकर्ता पत्र'
  ];

  if (client.docType === 'gift_deed_family') {
    mandatoryChecklist.push('पारिवारिक रक्त संबंध प्रमाणित करने हेतु परिवार जन आधार कार्ड अथवा राशन कार्ड प्रति');
  }
  if (client.docType === 'release_deed') {
    mandatoryChecklist.push('मूल खातेदार का मृत्यु प्रमाण पत्र एवं राजस्व विभाग/सक्षम न्यायालय द्वारा जारी कानूनी वारिसान प्रमाण पत्र (Pocession/Legal Heir Certificate)');
  }

  let title = 'विलेख प्रारूप';
  let body = '';

  switch (client.docType) {
    case 'sale_deed':
      title = 'विक्रय पत्र (बैनामा - Sale Deed)';
      body = `
================================================================================
                              विक्रय-पत्र (बैनामा)
                       (Sale Deed / Conveyance Deed)
================================================================================

यह विक्रय-पत्र आज दिनांक ${today} को अजमेर (राजस्थान) में निम्न पक्षों के मध्य निष्पादित किया गया:

प्रथम पक्ष (विक्रेता / हस्तांतरक):
${seller.name}, आत्मज ${seller.fatherName}, निवासी ${seller.address}, पहचान पत्र/आधार: ${seller.aadhaarOrPan}
(जिन्हें आगे इस दस्तावेज में "विक्रेता" कहा गया है, जिस संज्ञा में उनके वारिसान, प्रतिनिधि एवं उत्तराधिकारी सम्मिलित रहेंगे।)

एवं

द्वितीय पक्ष (क्रेता / हस्तांतरी):
${buyer.name}, आत्मज/पत्नी ${buyer.fatherName}, निवासी ${buyer.address}, पहचान पत्र/आधार: ${buyer.aadhaarOrPan}
(जिन्हें आगे इस दस्तावेज में "क्रेता" कहा गया है, जिस संज्ञा में उनके वारिसान, प्रतिनिधि एवं उत्तराधिकारी सम्मिलित रहेंगे।)

1. संपत्ति का विवरण:
यह कि विक्रेता उक्त अचल संपत्ति भूखंड/मकान संख्या ${p.plotOrKhasraNo || '___'}, खसरा सं. ${p.plotOrKhasraNo || '___'}, स्थित ${p.colonyOrLocality || '___'}, तहसील एवं जिला अजमेर का पूर्ण, एकमात्र, निर्विवाद एवं वैध स्वत्वधारी व काबिज है। जिसका कुल क्षेत्रफल ${p.areaSqYard || '___'} वर्ग गज (अथवा वर्ग मीटर) है।

2. संपत्ति की चौहद्दी (Boundaries):
- पूर्व में (East): ${p.boundaries.east || 'पड़ोसी का मकान / अन्य संपत्ति'}
- पश्चिम में (West): ${p.boundaries.west || 'सड़क / रास्ता'}
- उत्तर में (North): ${p.boundaries.north || 'अन्य भूखंड'}
- दक्षिण में (South): ${p.boundaries.south || 'अन्य भूखंड'}

3. प्रतिफल एवं भुगतान (Consideration & Payment):
यह कि विक्रेता को अपनी व्यक्तिगत व पारिवारिक आवश्यकताओं हेतु उक्त संपत्ति को बेचने की आवश्यकता थी, जिस पर द्वितीय पक्ष (क्रेता) ने उक्त संपत्ति को कुल प्रतिफल राशि ₹${p.considerationValue ? p.considerationValue.toLocaleString('en-IN') : '_______________'}/- (अक्षरे ____________________________________________ रुपये मात्र) में क्रय करना स्वीकार किया है। 
विक्रेता स्वीकार करता है कि उसने उक्त संपूर्ण प्रतिफल राशि क्रेता से चेक/ड्राफ्ट/ऑनलाइन माध्यम सं. ${cheque.chequeNo} बैंक ${cheque.bankName} दिनांक ${cheque.date} के द्वारा पूर्ण रूप से प्राप्त कर ली है और अब कोई राशि विक्रेता की क्रेता पर बकाया शेष नहीं है।

4. स्वत्व एवं भारमुक्तता (Clear Title):
विक्रेता प्रमाणित करता है कि उक्त संपत्ति हर प्रकार के बंधक, ऋण, लीज, अदालती कुर्की, वाद-विवाद, बैंक भार, सरकारी देयता अथवा कानूनी अड़चनों से सर्वथा मुक्त व साफ-सुथरी है। यदि भविष्य में विक्रेता के स्वत्व दोष के कारण क्रेता को कोई क्षति होती है तो उसकी समस्त क्षतिपूर्ति हेतु विक्रेता व उसकी अन्य संपत्तियां व्यक्तिगत रूप से उत्तरदायी रहेंगी।

5. आधिपत्य (Possession):
विक्रेता ने आज इस दस्तावेज के निष्पादन के साथ ही उक्त संपत्ति का वास्तविक, शांतिपूर्ण एवं भौतिक कब्ज़ा क्रेता को सौंप दिया है। क्रेता अब उक्त संपत्ति का स्वामी होकर स्वयं उपभोग करने, निर्माण करने, अथवा किसी अन्य को हस्तांतरित करने का पूर्ण वैधानिक अधिकारी है।

6. नामांतरण व राजस्व रिकॉर्ड:
क्रेता अपने नाम से नगर निगम अजमेर / अजमेर विकास प्राधिकरण (ADA) / संबंधित राजस्व विभाग में उक्त संपत्ति का नामांतरण (Mutation) कराने का पूर्ण रूप से अधिकृत रहेगा, जिसमें विक्रेता अथवा उसके वारिसान को कोई आपत्ति नहीं होगी।

7. गवाहान:
दोनों पक्षों ने स्वस्थ चित्त, बिना किसी अनुचित दबाव अथवा प्रलोभन के इस विक्रय पत्र को भली-भांति पढ़कर व सुनकर समझ लिया है और अपने-अपने हस्ताक्षर/अंगूठा निशानी सब-रजिस्ट्रार कार्यालय ${p.registrySubRegistrar || 'अजमेर'} के समक्ष दो गवाहों की उपस्थिति में अंकित किए हैं।
`;
      break;

    case 'gift_deed_family':
      title = 'दान पत्र - परिवार / रक्त संबंधी (Gift Deed - Family)';
      body = `
================================================================================
                                   दान-पत्र
                       (Gift Deed in favour of Relative)
================================================================================

यह दान-पत्र आज दिनांक ${today} को अजमेर में निष्पादित किया गया:

दानकर्ता (Donor):
${seller.name}, आत्मज ${seller.fatherName}, निवासी ${seller.address}
(जिन्हें आगे "दानकर्ता" कहा गया है)

एवं

दानग्रहीता (Donee):
${buyer.name}, आत्मज/पत्नी ${buyer.fatherName}, निवासी ${buyer.address}
(जिन्हें आगे "दानग्रहीता" कहा गया है)

1. संबंध एवं प्रेम का कारण:
यह कि दानग्रहीता, दानकर्ता का/की सगा/सगी [पुत्र / पुत्री / पत्नी / भाई / रक्त संबंधी] है। दानकर्ता का दानग्रहीता के प्रति अत्यधिक स्वाभाविक नैसर्गिक प्रेम, स्नेह एवं वात्सल्य है तथा दानग्रहीता सदैव दानकर्ता की आदरपूर्वक सेवा-सुश्रूषा करता/करती आ रही है।

2. संपत्ति विवरण:
भूखंड/मकान/कृषि संख्या: ${p.plotOrKhasraNo || '___'}, स्थित ${p.colonyOrLocality || '___'}, अजमेर, कुल क्षेत्रफल: ${p.areaSqYard || '___'} वर्ग गज।
चौहद्दी: पूर्व: ${p.boundaries.east || '___'}, पश्चिम: ${p.boundaries.west || '___'}, उत्तर: ${p.boundaries.north || '___'}, दक्षिण: ${p.boundaries.south || '___'}

3. दान का निष्पादन (Unconditional Gift):
अतः दानकर्ता बिना किसी प्रतिफल, धन, अथवा दबाव के, केवल अपने स्वाभाविक प्रेम एवं स्नेहवश अपनी पूर्ण इच्छा से उक्त संपत्ति दानग्रहीता को आजीवन स्वामित्व हेतु सहर्ष दान करता है।

4. स्वीकृति (Acceptance):
दानग्रहीता ने दानकर्ता द्वारा प्रदत्त इस दान को दानकर्ता के जीवनकाल में ही ससम्मान स्वीकार कर लिया है तथा दानकर्ता ने संपत्ति का भौतिक आधिपत्य भी दानग्रहीता को सौंप दिया है।

राजस्थान सरकार के नियमों के अनुसार यह दान निकट रक्त संबंधियों के मध्य होने से नियमानुसार रियायती स्टाम्प शुल्क चालान प्रस्तुत किया गया है।
`;
      break;

    case 'release_deed':
      title = 'हकत्याग पत्र (Release / Relinquishment Deed)';
      body = `
================================================================================
                                 हकत्याग-पत्र
                         (Relinquishment / Release Deed)
================================================================================

यह हकत्याग विलेख आज दिनांक ${today} को अजमेर में निष्पादित किया गया:

हकत्यागकर्ता (Releasor):
${seller.name}, आत्मज ${seller.fatherName}, निवासी ${seller.address}

पक्ष में (Releasee):
${buyer.name}, आत्मज/पत्नी ${buyer.fatherName}, निवासी ${buyer.address}

1. पृष्ठभूमि एवं पैतृक संपत्ति:
यह कि अचल संपत्ति भूखंड/मकान संख्या ${p.plotOrKhasraNo || '___'}, स्थित ${p.colonyOrLocality || '___'}, अजमेर हमारे पूर्वज स्वर्गीय [पूर्वज का नाम] की स्व-अर्जित/पैतृक संपत्ति थी, जिनके निधनोपरांत हम दोनों पक्ष संयुक्त सह-खातेदार/वारिसदार हुए।

2. स्वैच्छिक हकत्याग:
यह कि हकत्यागकर्ता अपने पारिवारिक प्रेम, सद्भाव एवं आपसी सहमति से उक्त संपत्ति में निहित अपने अविभाजित हिस्से का बिना किसी मौद्रिक प्रतिफल के पूर्ण रूप से हकत्याग करता है।

3. अधिकार मुक्ति:
आज के पश्चात उक्त संपत्ति पर केवल रिलीज पाने वाले पक्ष का ही संपूर्ण अधिकार रहेगा। हकत्यागकर्ता अथवा उसके किसी वारिस का भविष्य में उक्त संपत्ति में कोई स्वत्व, अधिकार अथवा दावा नहीं रहेगा।
`;
      break;

    case 'agreement_to_sell_possession':
    case 'agreement_to_sell_no_possession':
      title = 'इकरारनामा बैनामा (Agreement to Sell)';
      body = `
================================================================================
                               इकरारनामा बैनामा
                             (Agreement to Sell)
================================================================================

आज दिनांक ${today} को अजमेर में प्रथम पक्ष (विक्रेता) ${seller.name} एवं द्वितीय पक्ष (क्रेता) ${buyer.name} के मध्य तय पाया कि:

1. संपत्ति: भूखंड सं. ${p.plotOrKhasraNo || '___'}, ${p.colonyOrLocality || '___'}, अजमेर, क्षेत्रफल ${p.areaSqYard || '___'} वर्ग गज।
2. तय सौदा: कुल मूल्य ₹${p.considerationValue ? p.considerationValue.toLocaleString('en-IN') : '________'}/- नियत हुआ।
3. बयाना/अग्रिम: ₹${cheque.amount ? cheque.amount.toLocaleString('en-IN') : '________'}/- विक्रेता ने प्राप्त किए।
4. शेष रकम: रजिस्ट्री निष्पादन के समय सब-रजिस्ट्रार कार्यालय में दी जाएगी।
5. समयावधि: दोनों पक्ष निर्धारित 90 दिवस (अथवा परस्पर सहमति अनुसार) के भीतर नियमानुसार पूर्ण स्टाम्प शुल्क अदा कर बैनामा पंजीकृत कराने हेतु बाध्य रहेंगे।
`;
      break;

    default:
      title = `${client.docType} विलेख प्रारूप`;
      body = `
================================================================================
                           दस्तावेज़ प्रारूप: ${client.docType}
================================================================================
प्रथम पक्ष: ${seller.name}, पिता: ${seller.fatherName}, पता: ${seller.address}
द्वितीय पक्ष: ${buyer.name}, पिता: ${buyer.fatherName}, पता: ${buyer.address}
संपत्ति: ${p.plotOrKhasraNo}, ${p.colonyOrLocality}, अजमेर।
क्षेत्रफल: ${p.areaSqYard} वर्ग गज।
डीएलसी दर: ₹${p.dlcRate}/वर्ग गज।
`;
  }

  return {
    title,
    content: body.trim(),
    checklist: mandatoryChecklist
  };
}
